        'Girl ♀': isEn ? 'Girl ♀' : 'Девочка ♀',
        'Альфа-мальчик ♂': isEn ? 'Alpha Boy ♂' : 'Альфа-мальчик ♂',
        'Alpha Boy ♂': isEn ? 'Alpha Boy ♂' : 'Альфа-мальчик ♂',
